// Headless balancing: for every weapon find the DPS / big-slime-HP ratio (rho) at which
// the autopilot just clears a wave. Equal rho means equal power, so the balance factor of a
// weapon is its rho relative to the machine gun. Measured at a few weapon levels up to 31 (where
// the pulse interval stops shrinking). Also prints income per DPS for the pacing model.
//
//   node tools/balance.mjs [--write] [--seeds N] [--only id]
//   (--only with --write re-measures one weapon and keeps the other rows)
import { writeFileSync } from 'node:fs';
import { World } from '../js/world.js';
import { WEAPONS, buildStats } from '../js/weapons.js';
import { RNG } from '../js/rng.js';
import { botUpdate } from '../js/bot.js';
import { BALANCE as OLD_BALANCE } from '../js/balance.js';

const args = process.argv.slice(2);
const opt = (name, def) => { const i = args.indexOf(name); return i >= 0 ? args[i + 1] : def; };
const WRITE = args.includes('--write');
const SEEDS = +opt('--seeds', 8);
const ONLY = opt('--only', null);
const HP = 1000;
const DT = 1 / 60;

function runWave(def, level, rho, seed) {
  const w = new World(new RNG(seed * 7919 + 13), { events: false });
  w.loadLevel(1, HP);
  w.setLoadout([buildStats(def, level, rho * HP)]);
  const bot = {};
  for (let t = 0; t < 160; t += DT) {
    botUpdate(w, bot, DT);
    w.update(DT);
    if (w.lost) return false;
    if (w.waveState === 'inter') return true;
  }
  return false;
}

// money per second per nominal DPS while farming 3 waves
function income(def, level, rho, seed) {
  const w = new World(new RNG(seed), { events: false });
  w.loadLevel(1, HP);
  w.setLoadout([buildStats(def, level, rho * HP)]);
  const bot = {};
  let t = 0;
  while (t < 400 && w.waveNum <= 3 && !w.lost) { botUpdate(w, bot, DT); w.update(DT); t += DT; }
  return w.lost ? NaN : w.earned / t / (rho * HP);
}

function threshold(def, level) {
  let lo = 0.2, hi = 40;
  const need = Math.ceil(SEEDS * 0.8);
  for (let it = 0; it < 11; it++) {
    const mid = Math.sqrt(lo * hi);
    let ok = 0;
    for (let s = 1; s <= SEEDS; s++) if (runWave(def, level, mid, s)) ok++;
    if (ok >= need) hi = mid; else lo = mid;
  }
  return hi;
}

const list = ONLY ? WEAPONS.filter((w) => w.id === ONLY) : WEAPONS;
const ANCHORS = [1, 11, 21, 31];
const tables = {};
for (const level of ANCHORS) {
  const mg = threshold(WEAPONS[0], level);
  const out = {};
  console.log(`\nlevel ${level}: machine gun threshold rho = ${mg.toFixed(3)}`);
  for (const def of list) {
    const rho = def.id === 'mg' ? mg : threshold(def, level);
    out[def.id] = +(rho / mg).toFixed(3);
    const lam = [1.5, 3, 6].map((m) => (income(def, level, rho * m, 5) * (rho / mg)).toFixed(2));
    console.log(`${def.id.padEnd(10)} rho ${rho.toFixed(3)}  bal ${(rho / mg).toFixed(3)}  income per effective DPS @1.5x,3x,6x: ${lam.join(' ')}`);
  }
  tables[level] = out;
}

if (WRITE) {
  const row = (d) => (tables[ANCHORS[0]][d.id] !== undefined ? ANCHORS.map((l) => tables[l][d.id]) : OLD_BALANCE[d.id]);
  const rows = WEAPONS.filter((d) => row(d)).map((d) => `  ${d.id}: [${row(d).join(', ')}],`).join('\n');
  const src = `// Generated by tools/balance.mjs --write. Do not edit by hand.
// Nominal DPS multiplier per weapon at the weapon levels in BALANCE_LEVELS.
export const BALANCE_LEVELS = ${JSON.stringify(ANCHORS)};
export const BALANCE = {
${rows}
};
`;
  writeFileSync(new URL('../js/balance.js', import.meta.url), src);
  console.log('\nwrote js/balance.js');
}
